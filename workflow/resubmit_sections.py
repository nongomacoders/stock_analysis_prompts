"""Script to sequentially resubmit captured sections to OpenRouter (DeepSeek) and update the questions ledger.

Supports clearing previous responses, refreshing each section prompt with the latest
questions ledger generated by earlier sections, resuming pending/missing sections,
and persisting results in SQLite and Markdown briefs.
"""

