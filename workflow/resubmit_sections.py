def slugify(text: str) -> str:
    cleaned = re.sub(r"[^a-zA-Z0-9_\-]+", "_", text).strip("_")
    return cleaned[:40] if cleaned else "section"


def resubmit_sections(
    ticker: str,
    report: str | None = None,
    missing_only: bool = False,
    clear: bool = False,
    model: str | None = None,
    use_nitro: bool = False,
    delay_seconds: float = 2.0,
    db_path: str | Path | None = None,
) -> list[dict]:
    resolved_db = resolve_db_path(db_path)
    if not resolved_db.exists():
        raise FileNotFoundError(f"Database {resolved_db} does not exist.")

    comp_info = find_company_dir(ticker)
    if not comp_info:
        raise ValueError(f"Company '{ticker}' not found under companies/ directory.")
    sector, comp_dir = comp_info
    briefs_dir = comp_dir / "briefs"
    briefs_dir.mkdir(parents=True, exist_ok=True)

    base_model = model or get_openrouter_model()
    active_model = f"{base_model}:nitro" if use_nitro else base_model

    with connect_db(resolved_db) as conn:
        cur = conn.cursor()
        report_row = None
        if report:
            report_row = cur.execute(
                "SELECT sha256, filename, original_path, questions_ledger, doc_type FROM reports "
                "WHERE (filename LIKE ? OR original_path LIKE ? OR doc_type LIKE ? OR sha256 = ?) "
                "AND (original_path LIKE ? OR filename LIKE ?)",
                (f"%{report}%", f"%{report}%", f"%{report}%", report, f"%{ticker}%", f"%{ticker}%"),
            ).fetchone()
            if not report_row:
                report_row = cur.execute(
                    "SELECT sha256, filename, original_path, questions_ledger, doc_type FROM reports "
                    "WHERE filename LIKE ? OR original_path LIKE ? OR doc_type LIKE ? OR sha256 = ?",
                    (f"%{report}%", f"%{report}%", f"%{report}%", report),
                ).fetchone()

        if not report_row:
            report_row = cur.execute(
                "SELECT sha256, filename, original_path, questions_ledger, doc_type FROM reports WHERE original_path LIKE ? OR filename LIKE ?",
                (f"%{ticker}%", f"%{ticker}%"),
            ).fetchone()

        if not report_row:
            sources_dir = comp_dir / "sources"
            pdf_files = list(sources_dir.glob("*.pdf"))
            if pdf_files:
                report_row = cur.execute(
                    "SELECT sha256, filename, original_path, questions_ledger, doc_type FROM reports WHERE filename = ?",
                    (pdf_files[0].name,),
                ).fetchone()

        if not report_row:
            raise RuntimeError(f"No report record found in SQLite for ticker '{ticker}' (filter: {report}).")

        report_sha = report_row["sha256"]
        filename = report_row["filename"]
        doc_type = (report_row["doc_type"] if "doc_type" in report_row.keys() else "annual_report") or "annual_report"

        print(f"\nTarget report: {filename} (SHA: {report_sha[:12]}... | Role: {doc_type})")
        print(f"Company: {ticker.upper()} | Sector: {sector} | Model: {active_model}")

        if clear:
            print("\n[CLEAR] Clearing existing LLM responses and resetting questions ledger...")
            cur.execute(
                "UPDATE reports SET questions_ledger = '', updated_at = datetime('now') WHERE sha256 = ?",
                (report_sha,),
            )
            # Update all sections for this report
            sec_rows = cur.execute(
                "SELECT package_id, manifest_json FROM sections WHERE report_sha256 = ?",
                (report_sha,),
            ).fetchall()
            for s in sec_rows:
                manifest = json.loads(s["manifest_json"])
                manifest["review"] = {"model_brief": "not_run"}
                cur.execute(
                    "UPDATE sections SET llm_response = NULL, manifest_json = ?, updated_at = datetime('now') WHERE package_id = ?",
                    (json.dumps(manifest, ensure_ascii=False), s["package_id"]),
                )
            conn.commit()
            print(f"[CLEAR] Cleared responses across {len(sec_rows)} section(s). Questions ledger reset to empty.")

    # Retrieve all sections
    all_sections = list_sections(report_sha, db_path=resolved_db)
    if not all_sections:
        print(f"No sections found for report {report_sha} ({filename}).")
        return []

    if missing_only:
        sections = [s for s in all_sections if not s.llm_response or not s.llm_response.strip()
                    or s.manifest.get('review', {}).get('ledger_validation') == 'rejected']
        print(f"\n[RESUME] Found {len(sections)} pending section(s) without LLM responses (out of {len(all_sections)} total in {filename}).")
    else:
        sections = all_sections

    if not sections:
        print(f"\n[COMPLETE] All {len(all_sections)} sections in {filename} already have saved LLM responses!")
        return []

    print(f"\nProcessing {len(sections)} section(s) sequentially:")
    for s in sections:
        sub = f" — {s.subheading}" if s.subheading else ""
        has_resp = "✓" if (s.llm_response and s.llm_response.strip()) else "pending"
        print(f"  Sec {s.section_number:02d}: {s.heading}{sub} ({s.package_id}) [{has_resp}]")

    results = []

    for idx, sec in enumerate(sections, start=1):
        print(f"\n{'='*70}")
        sub_title = f" — {sec.subheading}" if sec.subheading else ""
        print(f"[{idx}/{len(sections)}] Section {sec.section_number:02d}: {sec.heading}{sub_title}")
        print(f"Package ID: {sec.package_id}")

        # Fetch current questions ledger from DB
        with connect_db(resolved_db) as conn:
            cur = conn.cursor()
            curr_rep = cur.execute("SELECT questions_ledger FROM reports WHERE sha256 = ?", (report_sha,)).fetchone()
            current_ledger = (curr_rep["questions_ledger"] if curr_rep else "") or ""

        # Dynamically refresh prompt with current ledger
        manifest = copy.deepcopy(sec.manifest)
        if "heading" not in manifest:
            manifest["heading"] = sec.heading
        if "subheading" not in manifest and sec.subheading:
            manifest["subheading"] = sec.subheading
        if "package_id" not in manifest:
            manifest["package_id"] = sec.package_id
        if "source" not in manifest:
            manifest["source"] = {"filename": filename, "sha256": report_sha}
        elif "sha256" not in manifest["source"]:
            manifest["source"]["sha256"] = report_sha
        if "selections" not in manifest:
            manifest["selections"] = sec.selections or []
        from section_capture.db import prepare_question_ledger
        manifest['ledger_contract'] = 1
        manifest["stored_questions"] = prepare_question_ledger(report_sha, resolved_db, for_prompt=True, context=manifest).strip() or None
        manifest["sector"] = sector
        texts = extract_selection_texts(manifest, selected_text=sec.selected_text, prompt=sec.prompt)
        refreshed_prompt = build_prompt(manifest, texts, sector=sector)

        # Update refreshed prompt in DB
        with connect_db(resolved_db) as conn:
            conn.execute(
                "UPDATE sections SET prompt = ?, manifest_json = ? WHERE package_id = ?",
                (refreshed_prompt, json.dumps(manifest, ensure_ascii=False), sec.package_id),
            )

        print(f"Prompt length: {len(refreshed_prompt):,} characters")
        print(f"Current questions ledger length: {len(current_ledger):,} characters")
        print(f"Sending query to OpenRouter ({active_model})...")

        start_time = time.perf_counter()
        response_text, raw_stats = query_openrouter(
            refreshed_prompt,
            model=active_model,
            timeout=180,
            return_details=True,
        )
        elapsed = time.perf_counter() - start_time

        gen_id = raw_stats.get("generation_id")
        tokens = {
            "prompt_tokens": raw_stats.get("prompt_tokens", 0),
            "completion_tokens": raw_stats.get("completion_tokens", 0),
            "total_tokens": raw_stats.get("total_tokens", 0),
        }
        cost_usd = raw_stats.get("cost_usd")

        # Attempt to get exact generation stats if generation_id exists
        if gen_id:
            try:
                gen_data = fetch_generation_stats(gen_id)
                if gen_data:
                    cost_usd = gen_data.get("total_cost") or cost_usd
                    if gen_data.get("tokens_prompt"):
                        tokens["prompt_tokens"] = gen_data.get("tokens_prompt")
                    if gen_data.get("tokens_completion"):
                        tokens["completion_tokens"] = gen_data.get("tokens_completion")
                    tokens["total_tokens"] = tokens["prompt_tokens"] + tokens["completion_tokens"]
            except Exception:
                pass

        if cost_usd is None and tokens["total_tokens"] > 0:
            cost_usd = estimate_cost(active_model, tokens["prompt_tokens"], tokens["completion_tokens"])

        # Save to SQLite and update questions ledger
        saved_sec, updated_ledger = save_section_llm_response(
            package_id=sec.package_id,
            llm_response=response_text,
            update_ledger=True,
            response_time_seconds=elapsed,
            cost_usd=cost_usd,
            tokens=tokens,
            model=active_model,
            db_path=resolved_db,
        )

        if saved_sec and saved_sec.manifest.get('review', {}).get('ledger_validation') == 'rejected':
            raise RuntimeError('Response preserved but ledger update rejected: '
                               + '; '.join(saved_sec.manifest['review']['ledger_errors']))

        # Save markdown brief to disk
        doc_prefix = ""
        dt_upper = doc_type.upper()
        if dt_upper in ("AFS", "SENS", "PRES"):
            doc_prefix = f"{dt_upper}_"

        slug = slugify(sec.heading)
        brief_filename = f"{doc_prefix}section_{sec.section_number:02d}_{slug}.md"
        brief_path = briefs_dir / brief_filename
        brief_content = f"# Section {sec.section_number:02d}: {sec.heading}{sub_title}\n\n"
        brief_content += f"> **Package**: `{sec.package_id}`  \n"
        brief_content += f"> **Report**: `{filename}` ({doc_type})  \n"
        brief_content += f"> **Model**: `{active_model}`  \n"
        brief_content += f"> **Execution Time**: {elapsed:.2f}s  \n"
        brief_content += f"> **Cost**: ${cost_usd:.4f}  \n" if cost_usd is not None else ""
        brief_content += f"> **Tokens**: {tokens.get('total_tokens', 0):,} total ({tokens.get('prompt_tokens', 0):,} prompt / {tokens.get('completion_tokens', 0):,} completion)  \n\n"
        brief_content += response_text
        brief_path.write_text(brief_content, encoding="utf-8")

        new_ledger_len = len(updated_ledger or "") if updated_ledger else len(current_ledger)
        print(f"[OK] Responded in {elapsed:.2f}s | Cost: ${cost_usd:.4f} | Tokens: {tokens.get('total_tokens', 0):,}")
        print(f"[OK] Response length: {len(response_text):,} chars | Saved to {brief_path.relative_to(PROJECT_ROOT)}")
        print(f"[OK] Stored Questions ledger updated: {new_ledger_len:,} chars (extracted: {bool(updated_ledger)})")

        results.append({
            "section_number": sec.section_number,
            "heading": sec.heading,
            "elapsed_s": round(elapsed, 2),
            "cost_usd": round(cost_usd, 4) if cost_usd else None,
            "tokens": tokens,
            "response_chars": len(response_text),
            "brief_path": str(brief_path),
            "ledger_chars": new_ledger_len,
        })

        if idx < len(sections) and delay_seconds > 0:
            print(f"Waiting {delay_seconds:.1f}s before next section...")
            time.sleep(delay_seconds)

    print(f"\n{'='*70}")
    print("ALL TARGET SECTIONS SUCCESSFULLY SUBMITTED & RECORDED")
    print(f"{'='*70}")
    print(f"{'Sec':<5} {'Heading':<30} {'Time(s)':<10} {'Cost($)':<10} {'Tokens':<10} {'Chars':<10}")
    print("-" * 75)
    for r in results:
        tot_tok = r["tokens"].get("total_tokens", 0)
        print(f"{r['section_number']:<5} {r['heading'][:28]:<30} {r['elapsed_s']:<10.2f} {r['cost_usd'] or 0.0:<10.4f} {tot_tok:<10,} {r['response_chars']:<10,}")
    print("-" * 75)

    return results


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Resubmit sections sequentially to OpenRouter.")
    parser.add_argument("ticker", help="Company ticker (e.g. PAN, LEW, CGR, IOC)")
    parser.add_argument("--report", default=None, help="Target specific report filename, doc role (e.g. AFS, IAR), or SHA256")
    parser.add_argument("--missing-only", action="store_true", help="Only submit sections that are missing an LLM response (preserves existing responses and ledger)")
    parser.add_argument("--clear", action="store_true", help="Clear existing LLM responses and reset questions ledger before starting")
    parser.add_argument("--no-clear", action="store_true", help="Do not clear existing responses before submitting (deprecated alias for default behavior)")
    parser.add_argument("--model", default=None, help="OpenRouter model (default: from config/env)")
    parser.add_argument("--nitro", action="store_true", help="Use :nitro routing")
    parser.add_argument("--delay", type=float, default=2.0, help="Delay between calls in seconds")
    parser.add_argument("--db", default=None, help="Path to analysis.sqlite")

    args = parser.parse_args()
    effective_clear = args.clear and not args.missing_only
    if args.no_clear:
        effective_clear = False
    resubmit_sections(
        ticker=args.ticker,
        report=args.report,
        missing_only=args.missing_only,
        clear=effective_clear,
        model=args.model,
        use_nitro=args.nitro,
        delay_seconds=args.delay,
        db_path=args.db,
    )
